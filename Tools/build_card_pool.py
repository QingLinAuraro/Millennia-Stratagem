BUFF_RATE = {"atk": 0.75, "hp": 0.5, "both": 0.6}

def center(dcs):
    if dcs <= 3:  return 2.0 * dcs
    if dcs <= 6:  return 6.0 + 1.5 * (dcs - 3)
    if dcs <= 9:  return 10.5 + 1.0 * (dcs - 6)
    return 13.5 + 0.5 * (dcs - 9)

def unit_adj(unit, dcs):
    if unit in ("弓兵", "器械"):
        return -min(2.0, dcs / 2.0)
    return 0.0

def acs_of(atk):
    # 严格按《部署价值表》G22：acost = ROUND(atk/3)，不设最低 1 费。
    # 1 ATK 单位行动费用为 0，靠行动次数（每回合 1 次）限制。
    return int(round(atk / 3.0))

def comp_of(atk, unit):
    if unit == "骑兵":
        return 0
    return int(2 * acs_of(atk) // 3)

def bounds(dcs, unit, atk):
    c = center(dcs) + unit_adj(unit, dcs) + comp_of(atk, unit)
    return round(c - 1, 3), round(c + 1, 3)

def kw_cost(kws, unit):
    s = 0.0
    for k in kws:
        if k == "闪击":
            continue
        s += KW_COST[k]
    if unit == "骑兵" and "闪击" not in kws:
        s -= 0.5
    return round(s, 3)

def buff_cost(na, nh):
    if na and nh: return round((na + nh) * BUFF_RATE["both"], 3)
    if na: return round(na * BUFF_RATE["atk"], 3)
    return round(nh * BUFF_RATE["hp"], 3)

def find_effect(text):
    if text not in EFFECT_COST:
        raise KeyError(f"效果未在基础表登记：{text}")
    return EFFECT_COST[text]

