def expand_units(rows):
    out = []
    for (cid, name, dyn, rar, unit, wt, dcs, atk, hp, kws, effs, quote, src) in rows:
        t = kw_cost(kws, unit) + sum(e[1] for e in effs)
        lo, hi = bounds(dcs, unit, atk)
        val = atk + hp + t
        out.append(dict(cid=cid, name=name, dyn=dyn, rar=rar, kind="兵牌", unit=unit, wt=wt,
                        dcs=dcs, acs=acs_of(atk), ap=(2 if (unit == "骑兵" or "连战" in kws) else 1),
                        atk=atk, hp=hp, rng=(2 if unit in ("弓兵", "器械") else 1),
                        kws=kws, effs=effs, quote=quote, src=src,
                        sigma=round(t, 3), lo=lo, hi=hi, val=val, dev=round(val - (lo + hi) / 2, 3)))
    return out

def expand_strats(rows):
    out = []
    for (cid, name, dyn, rar, dcs, text, cost, quote, src) in rows:
        out.append(dict(cid=cid, name=name, dyn=dyn, rar=rar, kind="策略牌", unit="—", wt="—",
                        dcs=dcs, acs=0, ap=None, atk=None, hp=None, rng=None,
                        kws=[], effs=[(text, cost)], quote=quote, src=src,
                        sigma=round(cost, 3), lo=None, hi=None, val=dcs,
                        dev=round(dcs - cost, 3)))
    return out

def split(rows):
    units = [r for r in rows if len(r) == 13]
    strats = [r for r in rows if len(r) == 9]
    return units, strats

QIN_UNITS, QIN_STRATS = split(QIN)
HAN_UNITS, HAN_STRATS = split(HAN)
GEN_UNITS, GEN_STRATS = split(GENERIC)

QIN_CARDS = expand_units(QIN_UNITS) + expand_strats(QIN_STRATS)
HAN_CARDS = expand_units(HAN_UNITS) + expand_strats(HAN_STRATS)
GEN_CARDS = expand_units(GEN_UNITS) + expand_strats(GEN_STRATS)
ALL = QIN_CARDS + HAN_CARDS + GEN_CARDS

# 稀有度 / 费用 / 类别统计
def tally(cards, key):
    d = {}
    for c in cards:
        d[c[key]] = d.get(c[key], 0) + 1
    return d

